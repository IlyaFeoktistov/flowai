"""
Конфигурационные константы MCP-агента: лимиты self-heal цикла (MAX_ATTEMPTS,
MAX_SELF_HEAL_ASKS, RECURSION_LIMIT), параметры моделей Ollama
(OLLAMA_KEEP_ALIVE, OLLAMA_NUM_CTX, MODEL_TEMPERATURE, OLLAMA_NUM_PREDICT,
JUDGE_NUM_PREDICT) и обрезка тул-результатов (TOOL_OUTPUT_CHAR_CAP).

Вынесены в отдельный модуль без зависимостей внутри mcp_agent, чтобы
DEBUG/константы можно было импортировать из любого другого подмодуля
(prompts.py, self_heal.py, agent_builder.py, agent.py) без риска циклического
импорта — ни одна из этих констант не переприсваивается через `global` вне
этого файла, так что plain `from mcp_agent.model_config import X` везде
безопасен (единственное исключение во всём агенте —
_SYSTEM_PROMPT_TOKENS_ESTIMATE в prompts.py, у него другой паттерн доступа,
см. комментарий там же).
"""
import os

import settings

# settings.get("debug") already resolves the priority (env DEBUG, if set,
# wins over whatever was last toggled via /settings — see settings.py) —
# this module just reads the result once at import time, same as every
# other constant here.
DEBUG = settings.get("debug")


# Пример: когда модель вызывает только git_diff_unstaged, не
# git_diff_staged — детерминированный вердикт верно отклоняет и даёт точную
# подсказку, что вызвать. Последняя попытка при MAX_ATTEMPTS=2 может тул НЕ
# вызвать — вместо этого текстом обосновать, почему он, по мнению модели, не
# нужен, и попытки кончаются раньше, чем модель реально исправится. Не
# "модели нужно меньше попыток, раз она умнее" — а ровно наоборот: подсказка
# верна, просто не хватает ещё одного шанса её исполнить. Подняли до 3
# — эта попытка достаётся модели дёшево (это тот же самый резидентный
# thread_id, лишь ещё один раунд), а не квадратично, как было бы с ростом
# MAX_ATTEMPTS у "перестроить план с нуля" в старом orchestrator.py.
MAX_ATTEMPTS = 3

# Сколько раз за один ход можно "самолечить" punt-to-user (модель отвечает
# текстовым вопросом вместо вызова ask_user — см. stream_chat) реальным
# интерактивным диалогом вместо ретрая. Каждое срабатывание продлевает
# max_attempts_effective на +1 (см. stream_chat), так что без потолка
# модель, которая раз за разом переспрашивает, могла бы растягивать ход
# бесконечно — 3 такие "спасённые" попытки за ход достаточно на практике и
# не даёт уйти в бесконечный цикл диалогов, если модель действительно не
# сходится ни на каком ответе.
MAX_SELF_HEAL_ASKS = 3

# Сколько модель держится в VRAM после ответа, прежде чем Ollama её выгрузит.
# Без этого каждый ход, разделённый паузой, платит полную перезагрузку весов
# в память — на локальной GPU это секунды впустую ещё до первого токена.
#
# qwen3-coder:30b весит на диске ~19 GB (Q4_K_M) — перезагрузка этого объёма
# заметно дороже, чем у прежних qwen2.5:7b/14b (~4.7-9 GB), а сама модель
# всё равно работает в основном на CPU (`ollama ps` показывает 79%/21%
# CPU/GPU), так что реальный throughput не страдает от того, что веса лежат
# и в RAM тоже. 32 GB RAM с запасом позволяют держать модель резидентной
# дольше между паузами в диалоге — подняли с 30m до 2h.
OLLAMA_KEEP_ALIVE = os.getenv("OLLAMA_KEEP_ALIVE", "2h")

# Лог Ollama (journalctl -u ollama) показывает это напрямую при 8192:
#   n_ctx_slot = 8192, n_keep = 4, task.n_tokens = 8571
#   "truncating input prompt" limit=4098 ... new=4098
# n_keep=4 — сколько ТОКЕНОВ с начала промпта сохраняется при переполнении
# (это НЕ настраивается через langchain_ollama — ни ChatOllama, ни его
# options_dict такого параметра не знают). System-промпт сейчас ~2813
# токенов (см. _SYSTEM_PROMPT_TOKENS_ESTIMATE) — при переполнении он ПОЧТИ
# ВЕСЬ вылетает из контекста вместе с исходной задачей, остаётся только
# хвост (последние тул-результаты). Это причина большинства случаев, когда
# модель "забывает задачу и зацикливается на последней случайной детали" —
# не блуждание модели, а буквальное обрезание промпта.
#
# 8192 хватало, пока промпт был короче и TOOL_OUTPUT_CHAR_CAP был меньше;
# 16384 было компромиссом под qwen3:14b — ту модель ещё имело смысл
# частично удерживать на GPU (6 GB VRAM), и лишний контекст рисковал
# вытолкнуть её в чистый CPU.
#
# qwen3-coder:30b (MoE, ~3B активных параметров на токен, 19 GB весов) эту
# развилку убирает: `ollama ps` и так показывает 79%/21% CPU/GPU — модель
# уже большей частью на CPU независимо от num_ctx, так что расширение
# контекста не роняет её ещё сильнее в CPU, как роняло бы плотную модель.
# Стоимость увеличения контекста здесь — это в основном KV-cache в RAM
# (grouped-query attention, немного kv-голов), а не compute: на 32768
# токенов это грубо ~3 GB.
#
# `ollama show qwen3-coder:30b` отдаёт "context length 262144" — это
# НАТИВНЫЙ потолок модели (256K, расширяемо до 1M через YaRN), а не то, что
# реально влезает на этой машине. Фактический бюджет: это WSL2-инстанс с
# жёстким потолком памяти 24 GB (`/mnt/c/Users/*/.wslconfig`,
# `[wsl2] memory=24GB`) — `free -h` показывает ~21 GB available. Из них ~15 GB
# уже держат CPU-резидентную часть весов (79% от 19 GB), так что на KV-cache
# реально свободно ~6 GB, ПРЕЖДЕ чем начнётся своп (своп у WSL2-инстанса всего
# 6 GB и он на диске — переполнение сюда не "чуть медленнее", а на порядок
# медленнее, вплоть до подвисания хода на минуты). 6 GB KV-cache при курсе
# ~3 GB/32768 токенов — это и есть потолок ~65536, дальше без добавления RAM
# (либо через .wslconfig, если у хоста Windows есть свободная физическая
# память сверх текущих 24 GB, либо через уменьшение квантизации весов) не
# поднять. Потолок установлен ровно на этом практическом пределе, а не на
# теоретическом максимуме модели — 262144 на этом железе гарантированно
# уронит машину в своп на первом же длинном ходе.
#
# Понижено до 30000 — не из-за риска свопа (65536 был безопасен по расчёту
# выше, запас там был), а чтобы совпадать с settings.num_ctx (тот дефолт
# тоже понижен под expert_streaming.py: на 65536 autofit hot-store
# экспертов не находил вообще ни одного слота). Router/self_heal грузят
# СВОЙ отдельный процесс модели через обычный Ollama-путь (см.
# settings.py:num_ctx про то, почему это разные тумблеры) — при разных
# значениях этой и той константы одновременно резидентны ДВА полных
# экземпляра модели (~20 GB весов каждый) с разным num_ctx: VRAM уходит с
# ~4 ГБ занятых до 29 МиБ свободных. Держать оба потолка одинаковыми — не
# обязательное требование
# движка, а способ не платить за две одновременные полные загрузки модели
# без необходимости.
OLLAMA_NUM_CTX = int(os.getenv("OLLAMA_NUM_CTX", "30000"))

# top_p/top_k НЕ переопределялись нигде в agent_builder.py — по умолчанию
# (None у ChatOllama) это означало, что реально применялись значения из
# Modelfile модели (top_p=0.8, top_k=20 — официальные цифры Alibaba под
# бенчмарки). Community-треды по интеграции qwen3-coder:30b с агентными
# обвязками (Cline/Roo/llama.cpp) сообщают top_p=0.9/top_k=40 как более
# надёжные именно для агентного tool-use — уже режут длинный хвост
# маловероятных токенов, но чуть меньше сужают выбор, чем 0.8/20. Это НЕ
# официальная рекомендация Qwen и не проверено на реальных ходах в этом
# проекте — если после включения не видно изменения (или видно ухудшение)
# частоты "потерянного <tool_call>" в self_heal.py, первым делом откатить
# именно это, не остальные параметры сэмплинга.
TOP_P = float(os.getenv("MODEL_TOP_P", "0.9"))
TOP_K = int(os.getenv("MODEL_TOP_K", "40"))

# _CompactResearchMiddleware (mcp_agent/compaction.py) может сжать историю
# сразу после первого успешного write, даже если реальной необходимости
# нет — например: "3 messages -> digest (108 chars) + 2 kept verbatim" на
# истории едва ли в пару тысяч токенов (system-промпт ~2800 + один mkdir)
# при num_ctx уже 65536. Это происходит потому, что старый триггер был
# "есть УСПЕШНЫЙ write в истории" (см. _last_write_result_index), а не
# "история реально приближается к пределу". Ноль риска ЗДЕСЬ (write и его
# результат всегда остаются verbatim, см. модуль), но и ноль пользы — плюс
# каждое такое срабатывание превращает то, что модель могла бы прочитать
# дословно, в пересказ (см. docstring модуля — там разобран случай, где
# именно такой пересказ стоил 3 лишних тул-вызовов). Порог тогда стал
# долей от num_ctx (COMPACT_HISTORY_CTX_RATIO=0.5) — та константа с тех пор
# убрана: 400-я ошибка ("request exceeds context size") показала,
# что compaction.py._needs_compaction никогда не считал ни system-промпт,
# ни схемы тулов (LangChain's ModelRequest.messages их не включает вообще)
# — доля от num_ctx маскировала эту дыру щедрым запасом чисто случайно,
# пока набор тулов не вырос настолько, что дыра стала больше запаса. Порог
# теперь буквальный: num_ctx минус OLLAMA_NUM_PREDICT (генерации самого
# этого вызова тоже нужно поместиться в то же окно) минус плоский запас
# под неточность chars//4 — см. _needs_compaction в compaction.py.

# Ollama-дефолт (~0.8) не задавался явно нигде в этом файле. При дефолтной
# температуре edit_file получал невалидный JSON в 4 из 4 прогонов (то целый объект
# вместо массива, то и вовсе кривой XML настолько, что падал сам
# Ollama-клиент — см. ollama.ResponseError выше). Structured tool-calling
# (JSON args, XML-теги вызова) — не творческая задача, где разнообразие
# нужно, а задача "воспроизвести точный формат" — ниже temperature снижает
# шанс отклониться от него. Судья (JUDGE) получает то же значение по той же
# причине: вердикт на одинаковых входных данных не должен "плавать" между
# похожими прогонами.
MODEL_TEMPERATURE = float(os.getenv("MODEL_TEMPERATURE", "0.2"))

# Analyzer's итоговый инвентарь (длинный список "### Файл: ...
# **Назначение:** ... **Классы/функции:**" блоков, один на каждый
# прочитанный файл) может зациклиться под конец — модель начинает дословно
# повторять уже написанные блоки (например BackgroundJobManager ->
# BackgroundJobManagerInterface -> BackgroundJobResult -> ... -> снова
# BackgroundJobManager, до самого num_predict) вместо того, чтобы
# остановиться. Ollama/llama.cpp-дефолт repeat_last_n=64 токенов — короче
# ОДНОГО такого блока (100-150+ токенов на файл), так что штраф за повтор
# физически не видит совпадение с блоком, написанным чуть раньше. Подняли
# repeat_last_n настолько, чтобы окно перекрывало несколько блоков разом, и
# слегка увеличили repeat_penalty (дефолт 1.1) — сильнее наказывает именно
# повтор уже сгенерированного, а не общее разнообразие (за то же самое уже
# отвечает низкая MODEL_TEMPERATURE выше).
REPEAT_PENALTY = float(os.getenv("REPEAT_PENALTY", "1.2"))
REPEAT_LAST_N = int(os.getenv("REPEAT_LAST_N", "512"))

# Верхняя граница длины ОТВЕТА (не считая мыслей/тул-коллов) — без неё модель
# может сгенерировать значительно более длинный текст, чем нужно по задаче,
# и каждый лишний токен — это реальное время генерации. 1024 резало вживую на
# задаче "разбери большой дифф + найди баги" — ответ обрывался на середине
# предложения, не дойдя даже до второй половины задачи. 2048 было
# компромиссом для более слабых моделей (qwen2.5/qwen3 7b-14b).
#
# qwen3-coder:30b тянет более длинные связные ответы (например, полный
# разбор многофайлового диффа или переписанный файл целиком) — подняли до
# 4096, чтобы такие ответы не обрывались на полуслове так же, как резало
# 1024 в описанном выше случае. При ~3B активных параметрах (MoE) лишние
# токены здесь дешевле, чем были бы у плотной модели того же размера.
OLLAMA_NUM_PREDICT = int(os.getenv("OLLAMA_NUM_PREDICT", "4096"))

# Judge из _semantic_check возвращает только {"relevant": bool, "reason": "..."}
# — коротким лимитом отсекаем ситуацию, когда маленькая модель вместо JSON
# начинает "рассуждать вслух" на несколько абзацев.
JUDGE_NUM_PREDICT = int(os.getenv("JUDGE_NUM_PREDICT", "200"))

# router.py:answer_casual — не тот же лимит, что OLLAMA_NUM_PREDICT (тот
# тюнингован под задачи с тулами — целиком переписанный файл, разбор
# многофайлового диффа, где реально нужны тысячи токенов связного текста).
# Простой вопрос без единого тула (например "напиши первые строки Анны
# Карениной") с max_tokens=4096 может свалиться в несвязный бардак на
# несколько тысяч токенов — рефлексия вслух, дублирующиеся абзацы,
# наконец finish_reason="length" (съеден весь бюджет, ни разу не
# остановившись сама). Воспроизведено сырым curl'ом прямо к backend'у, в
# обход всего приложения — с тем же сэмплингом, но max_tokens=300-400, тот
# же вопрос давал чистый короткий ответ каждый раз: модели просто не
# хватало длины добраться до точки срыва. Короткий лимит здесь не лечит
# саму склонность к срыву (см. разбор в _CASUAL_HISTORY_WINDOW/
# router.py:answer_casual), а ограничивает урон — если она всё же
# сорвётся, это будет несколько сотен токенов мусора, а не 4096.
CASUAL_NUM_PREDICT = int(os.getenv("CASUAL_NUM_PREDICT", "1024"))

# ask_user_tool.py:_AskUserFinalizeNumPredictMiddleware — Planner's turn
# right after ask_user returns must only RESTATE the plan it already put
# in the ask_user question (prompts.py's planner prompt), never derive a
# new one — it's plain text, not tool-call args, so it never needs
# Coder-length output (full file rewrites). Instead of restating, Planner
# can re-derive a new plan from scratch and ramble for close to
# OLLAMA_NUM_PREDICT's full 4096-token (~2min) budget instead of stopping
# — same "small model + big budget = incoherent runaway" failure
# CASUAL_NUM_PREDICT's docstring above already documents for
# router.py:answer_casual. Same fix, same caveat: this limits the damage (worst case a
# few hundred tokens more, not 4096) — it does not cure the re-deriving
# itself, see the middleware's own docstring for the mechanical guard
# that targets that part.
ASK_USER_FINALIZE_NUM_PREDICT = int(os.getenv("ASK_USER_FINALIZE_NUM_PREDICT", "1536"))

# Без явного лимита create_agent's ReAct-луп может звать тулы неограниченно
# много раз за один ainvoke(), если модель не сходится к финальному ответу —
# на медленной локальной модели это может означать реальное ожидание в
# десятки минут вместо честной быстрой ошибки. LangGraph сам считает
# каждый шаг графа (не только tool-calls) — берём с запасом, но конечным.
#
# 100 шагов графа может уйти всего на ~34 РЕАЛЬНЫХ вызова тулов
# (self_heal добавляет судью на каждый круг, plus узлы мидлвари — каждый
# вызов тула стоит НЕСКОЛЬКО шагов графа, не один), и это не зацикливание:
# агент может честно копать одну длинную цепочку зависимостей и
# остановиться в шаге от реального ответа. 150 — не решает саму
# причину (дорогие угадывающие search_code-паттерны, thinking-латентность у
# Qwen3), но даёт немного больше воздуха на действительно многофайловые
# расследования; см. lsp (быстрее находит нужное, чем угадывание regex) и
# delegate (см. delegate_tool.py — свой ОТДЕЛЬНЫЙ бюджет шагов под сабагента,
# не тратящий этот же лимит на разведку).
RECURSION_LIMIT = 150

# Сабагент delegate_tool.py:delegate получает СВОЙ, отдельный от основного
# разговора бюджет шагов — меньше главного (RECURSION_LIMIT), потому что
# ему делегируют ОДНУ узкую задачу ("проследи X через Job/Service/
# Repository"), а не весь ход целиком, и он не должен иметь возможность в
# одиночку съесть время, сравнимое с основным лимитом.
DELEGATE_RECURSION_LIMIT = 60

# Per-роль бюджеты для пайплайна Router->Analyzer->Planner->Coder->Verifier
# (mcp_agent/pipeline.py, mcp_agent/roles.py) — тот же принцип, что уже
# доказал себя на DELEGATE_RECURSION_LIMIT выше: каждой роли достаётся
# ОДНА узкая задача, а не весь ход целиком, так что общий RECURSION_LIMIT=150
# для неё избыточен и рискует замаскировать зацикливание внутри одной роли
# долгим "честным" исчерпанием чужого бюджета.
#
# Analyzer — только читает/ищет, самая широкая по объёму работы роль (может
# звать read/search параллельно много раз за раунд) — ближе к основному
# RECURSION_LIMIT, чем к узкому DELEGATE_RECURSION_LIMIT.
#
# На реальной многофайловой задаче 100 может не хватить — но с delegate,
# убранным из тулов Analyzer'а (см. agent_builder.py:_build_role_agent),
# весь бюджет тратится на ОДИН прозрачный контекст вместо того, чтобы
# часть его пряталась в непрозрачном вложенном вызове. Поднято до
# основного RECURSION_LIMIT.
ANALYZER_RECURSION_LIMIT = 150
# Planner не пишет код и не гоняет bash — только читает при необходимости
# уточнить, строит план и должен закончиться ask_user.
#
# При 60 Planner может исчерпать бюджет и на РЕТРАЕ перечитывать те же
# самые диапазоны строк, что и в первой попытке (ретрай-дайджест сам по
# себе не спасает, см. также фикс в agent.py:_summarize_round — там же
# теперь диапазоны строк, а не только пути). Поднято до
# ANALYZER_RECURSION_LIMIT: если Analyzer
# передаёт сниппеты кода (см. prompts.py:_analyzer_system_prompt), Planner
